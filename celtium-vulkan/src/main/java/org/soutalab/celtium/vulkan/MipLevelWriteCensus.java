package org.soutalab.celtium.vulkan;

/**
 * Every write that lands pixels in a {@link VulkanGlTexture} mirror level, counted per level
 * across the whole process (R-104): how many writes each mip level received, and how many bytes
 * they put into it.
 * <p>
 * The per-mirror provenance in {@code VulkanGlTexture} ({@code levelWrites}) already answers
 * "which levels did this texture's writes touch", but it is printed only in the mirror dump, one
 * texture at a time. The question R-104 leaves open is a run-level one - did the atlas mirror's
 * chain get built by whole-image uploads, or was the mirror established by patches alone, so the
 * levels above the patches' depth were never written at all - and it needs one aggregate a leg
 * can read off the verification summary without a per-texture dump. That is this census. It is
 * always on and is read through {@link #summary()} beside the texture upload counters in
 * {@code BackendDiagnostics}; it is not gated by the {@code textureDiagnostics} flag.
 * <p>
 * What a "write" is, per upload path - the same seats that record the per-mirror provenance, so
 * the two accounts cannot drift apart:
 * <ul>
 * <li>A whole-image upload counts level 0 once with the copied byte count, and every level above
 * it once with that level's full byte size: the chain above level 0 is regenerated by blitting,
 * and a blit writes the whole level. The service route counts at enqueue, matching
 * {@code recordWholeImageWrite}'s own convention.</li>
 * <li>A single-level upload (the game's own pixels for one level, direct or via the service)
 * counts that one level with the uploaded byte count.</li>
 * <li>A producer patch counts each level it supplied, with the staged byte count of that
 * level's region - the same {@code bytes} the patch's staging offsets are packed from.</li>
 * </ul>
 * Bytes are RGBA8 bytes: a mirror texel is four bytes ({@code VulkanGlTexture.BYTES_PER_PIXEL}),
 * which is the unit every upload path in the mirror already converts to. Levels are capped at
 * {@link #MAX_LEVELS}; a write to a level outside the table is bucketed in the above-cap totals
 * rather than dropped, so the census never silently loses a write it cannot place.
 */
public final class MipLevelWriteCensus {

    /** Deepest level the table resolves. A 16384-wide mirror's full chain is 15 levels. */
    public static final int MAX_LEVELS = 16;

    private static final long[] WRITE_COUNTS = new long[MAX_LEVELS];
    private static final long[] WRITE_BYTES = new long[MAX_LEVELS];
    private static long aboveCapWrites;
    private static long aboveCapBytes;

    private MipLevelWriteCensus() {
    }

    /** One write of {@code bytes} bytes into {@code level}. */
    public static synchronized void noteWrite(int level, long bytes) {
        if (level >= 0 && level < MAX_LEVELS) {
            WRITE_COUNTS[level]++;
            WRITE_BYTES[level] += bytes;
        } else {
            aboveCapWrites++;
            aboveCapBytes += bytes;
        }
    }

    /**
     * One whole-image upload: level 0 was copied ({@code levelZeroBytes} bytes) and every level
     * above it was regenerated by blitting, which writes each level in full - so level {@code l}
     * accounts {@code max(1, width >> l) * max(1, height >> l) * bytesPerTexel} bytes, the same
     * clamped halving the mirror's own level extents use.
     */
    public static synchronized void noteWholeImage(int width, int height, int levels, int bytesPerTexel,
            long levelZeroBytes) {
        noteWrite(0, levelZeroBytes);
        for (int level = 1; level < levels; level++) {
            long levelBytes = (long) Math.max(1, width >> level) * (long) Math.max(1, height >> level)
                    * (long) bytesPerTexel;
            noteWrite(level, levelBytes);
        }
    }

    /** {@return how many writes {@code level} has received}, 0 for a level outside the table. */
    public static synchronized long writeCount(int level) {
        return level >= 0 && level < MAX_LEVELS ? WRITE_COUNTS[level] : 0L;
    }

    /** {@return how many bytes the writes into {@code level} carried}, 0 outside the table. */
    public static synchronized long writeBytes(int level) {
        return level >= 0 && level < MAX_LEVELS ? WRITE_BYTES[level] : 0L;
    }

    /** {@return writes whose level fell outside the table}. */
    public static synchronized long aboveCapWrites() {
        return aboveCapWrites;
    }

    /** {@return bytes whose level fell outside the table}. */
    public static synchronized long aboveCapBytes() {
        return aboveCapBytes;
    }

    /**
     * {@return the one-line reading for the verification summary}:
     * {@code 0:93/25165824 1:93/6291456} is level:count/bytes per written level, in level order.
     * Levels nobody wrote are omitted, so a chain established by patches alone reads as entries
     * that stop at the patches' depth - which is exactly the R-104 discrimination. An empty
     * string means no mirror level was written yet.
     */
    public static synchronized String summary() {
        StringBuilder text = new StringBuilder();
        for (int level = 0; level < MAX_LEVELS; level++) {
            if (WRITE_COUNTS[level] > 0) {
                if (text.length() > 0) {
                    text.append(' ');
                }
                text.append(level).append(':').append(WRITE_COUNTS[level]).append('/').append(WRITE_BYTES[level]);
            }
        }
        if (aboveCapWrites > 0) {
            if (text.length() > 0) {
                text.append(' ');
            }
            text.append("aboveCap=").append(aboveCapWrites).append('/').append(aboveCapBytes);
        }
        return text.toString();
    }
}
